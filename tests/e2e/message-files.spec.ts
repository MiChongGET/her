import { mkdtempSync, rmSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { _electron, expect, test } from '@playwright/test'
import { startFixtureServer } from '../pi-sdk/wire'

test('images and files remain in the sent user message immediately, during generation and after reload', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'her-message-files-'))
  const imagePath = join(directory, 'picture.png'), textPath = join(directory, 'notes.txt')
  copyFileSync(resolve('tests/fixtures/documents/scan.png'), imagePath)
  writeFileSync(textPath, 'attachment display fixture')
  const documents = ['text.pdf', 'tiny.docx', 'tiny.xlsx']
  for (const name of documents) copyFileSync(resolve('tests/fixtures/documents', name), join(directory, name))
  let release!: () => void
  const reply = new Promise<void>(resolve => { release = resolve })
  const server = await startFixtureServer('openai', 'text', { beforeReply: () => reply })
  const env = Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined && entry[0] !== 'ELECTRON_RUN_AS_NODE'))
  const app = await _electron.launch({ ...(process.env.HER_TEST_APP_EXECUTABLE ? { executablePath: process.env.HER_TEST_APP_EXECUTABLE, args: [] } : { args: [resolve('.')] }), env: { ...env, HER_DATA_DIR: join(directory, 'data') } })
  try {
    const page = await app.firstWindow()
    await expect(page.getByText('文字与附件', { exact: true })).toBeVisible()
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(850, 620))
    await page.evaluate(async baseUrl => {
      const saved = await window.her.saveProfile({ name: '附件验证 · 模拟服务', protocol: 'openai', baseUrl, model: 'test-model', contextWindow: 128000, authMethod: 'none', models: [{ id: 'test-model', multimodal: true }] })
      await window.her.selectProfile(saved.id)
      await window.her.createConversation()
    }, server.baseUrl + '/v1')
    await page.reload()
    await page.evaluate(() => { const input = document.createElement('input'); input.type = 'file'; input.multiple = true; input.id = 'disk-files'; input.hidden = true; document.body.append(input) })
    await page.locator('#disk-files').setInputFiles([imagePath, textPath, ...documents.map(name => join(directory, name))])
    await page.evaluate(() => {
      const transfer = new DataTransfer()
      transfer.items.add(document.querySelector<HTMLInputElement>('#disk-files')!.files![0])
      document.querySelector('.composer-area')!.dispatchEvent(new DragEvent('drop', { bubbles: true, dataTransfer: transfer }))
    })
    await expect(page.getByRole('button', { name: '移除 picture.png' })).toBeVisible()
    await expect(page.locator('.attachments-preview .attachment-thumbnail')).toBeVisible()
    const chipBounds = await page.locator('.attachments-preview .file-chip').boundingBox()
    const composerBounds = await page.locator('.composer').boundingBox()
    expect(Math.abs(chipBounds!.x - composerBounds!.x)).toBeLessThan(3)
    await expect(page.getByRole('dialog', { name: '当前资料授权' })).toBeHidden()
    const layoutEvidence = resolve('experiments/life-companion-ui-acceptance/screenshots'); mkdirSync(layoutEvidence, { recursive: true })
    await page.screenshot({ path: join(layoutEvidence, `${process.env.HER_TEST_APP_EXECUTABLE ? 'package' : 'source'}-attachment-draft-850x620.png`) })
    await page.getByText('文字与附件', { exact: true }).click()
    await page.getByRole('button', { name: '查看当前资料授权' }).click()
    await expect(page.getByRole('dialog', { name: '当前资料授权' })).toBeVisible()
    await expect(page.getByRole('button', { name: '关闭资料授权' })).toBeFocused()
    const openComposerBounds = await page.locator('.composer').boundingBox()
    expect(Math.abs(openComposerBounds!.y - composerBounds!.y)).toBeLessThan(3)
    await page.screenshot({ path: join(layoutEvidence, `${process.env.HER_TEST_APP_EXECUTABLE ? 'package' : 'source'}-grants-flyout-850x620.png`) })
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog', { name: '当前资料授权' })).toBeHidden()
    await page.evaluate(() => {
      const transfer = new DataTransfer()
      const files = document.querySelector<HTMLInputElement>('#disk-files')!.files!
      for (let index = 1; index < files.length; index++) transfer.items.add(files[index])
      document.querySelector('.composer-area')!.dispatchEvent(new DragEvent('drop', { bubbles: true, dataTransfer: transfer }))
    })
    await expect(page.getByRole('button', { name: '移除 notes.txt' })).toBeVisible()
    await page.getByRole('textbox', { name: '消息', exact: true }).fill('看看这张图片和这份文件')
    await page.getByRole('button', { name: '发送', exact: true }).click()
    const user = page.locator('.message-user').last()
    await expect(user.getByRole('button', { name: '打开来源 picture.png' })).toBeVisible()
    for (const name of ['notes.txt', ...documents]) await expect(user.getByRole('button', { name: `打开来源 ${name}` })).toBeVisible()
    await expect(user.getByAltText('picture.png')).toBeVisible()
    await expect.poll(() => user.getByAltText('picture.png').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
    const imageBox = await user.getByAltText('picture.png').boundingBox()
    expect(imageBox!.width / imageBox!.height).toBeCloseTo(3, 1)
    const pictureName = await user.getByRole('button', { name: '打开来源 picture.png' }).boundingBox()
    const textName = await user.getByRole('button', { name: '打开来源 notes.txt' }).boundingBox()
    expect(imageBox!.y + imageBox!.height).toBeLessThanOrEqual(pictureName!.y)
    expect(pictureName!.y + pictureName!.height).toBeLessThanOrEqual(textName!.y)
    await expect.poll(() => server.requests.length).toBe(1)
    expect(JSON.stringify(server.requests[0].body)).toContain('data:image/png;base64,')
    await page.reload()
    await expect(user.getByAltText('picture.png')).toBeVisible()
    for (const name of ['notes.txt', ...documents]) await expect(user.getByRole('button', { name: `打开来源 ${name}` })).toBeVisible()
    release()
    await expect(page.locator('.message-assistant[data-status="complete"]')).toHaveCount(1)
    await page.reload()
    await expect(user.getByAltText('picture.png')).toBeVisible()
    for (const name of ['notes.txt', ...documents]) await expect(user.getByRole('button', { name: `打开来源 ${name}` })).toBeVisible()
    const evidence = resolve('.taste-skill/message-files'); mkdirSync(evidence, { recursive: true })
    await page.screenshot({ path: join(evidence, 'sent-files.png') })
    await expect(page.getByRole('textbox', { name: '消息', exact: true })).toBeInViewport()
    const workspaceEvidence = resolve('experiments/companion-workspace/screenshots'); mkdirSync(workspaceEvidence, { recursive: true })
    await page.screenshot({ path: join(workspaceEvidence, `${process.env.HER_TEST_APP_EXECUTABLE ? 'package' : 'source'}-attachments-850x620.png`) })
  } finally { release(); await app.close(); await server.close(); rmSync(directory, { recursive: true, force: true }) }
})
