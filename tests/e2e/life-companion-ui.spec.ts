const env = Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined && entry[0] !== 'ELECTRON_RUN_AS_NODE'))
const evidence = resolve('.superpowers/sdd/2026-10-23-life-companion-ui-implementation/electron')
const evidencePrefix = process.env.HER_TEST_APP_EXECUTABLE ? 'package' : 'source'

async function launch(directory: string) {
  const executablePath = process.env.HER_TEST_APP_EXECUTABLE
  const app = await _electron.launch({ ...(executablePath ? { executablePath, args: [] } : { args: [resolve('.')] }), env: { ...env, HER_DATA_DIR: directory } })
  const page = await app.firstWindow()
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1034, 749))
  await expect(page.getByRole('button', { name: '日常', exact: true })).toHaveAttribute('aria-current', 'page')
  return { app, page }
}

test('titlebar_brand_precedes_sidebar_toggle_and_tracks_divider', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'her-titlebar-'))
  mkdirSync(evidence, { recursive: true })
  const { app, page } = await launch(directory)
  try {
    await expect(page.locator('.topbar-dots')).toHaveCount(0)
    const logo = page.locator('.topbar-name .her-mark')
    const toggle = page.getByRole('button', { name: '隐藏侧栏' })
    const divider = page.getByRole('separator', { name: '调整侧栏宽度' })
    const checkAlignment = async () => {
      const [brand, control, line] = await Promise.all([logo.boundingBox(), toggle.boundingBox(), divider.boundingBox()])
      expect(brand).not.toBeNull(); expect(control).not.toBeNull(); expect(line).not.toBeNull()
      expect(brand!.x + brand!.width).toBeLessThan(control!.x)
      expect(line!.x - (control!.x + control!.width)).toBeGreaterThanOrEqual(0)
      expect(line!.x - (control!.x + control!.width)).toBeLessThanOrEqual(10)
    }
    await checkAlignment()
    await page.screenshot({ path: join(evidence, `${evidencePrefix}-titlebar.png`) })
    await divider.focus()
    await divider.press('ArrowRight')
    await checkAlignment()
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(850, 620))
    await checkAlignment()
    await page.screenshot({ path: join(evidence, `${evidencePrefix}-titlebar-850x620.png`) })
  } finally { await app.close(); rmSync(directory, { recursive: true, force: true }) }
})

