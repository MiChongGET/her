test('confirmed_daily_handoff_survives_restart_without_model_request', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'her-life-handoff-'))
  const paths = dataPaths(directory)
  const store = new HerStore(paths.database)
  const daily = store.ensureDailyConversation()
  store.saveService({ id: 'local-test', name: '隔离本地服务', protocol: 'openai', baseUrl: 'http://127.0.0.1:1/v1', defaultModel: 'test-model', authMethod: 'none',
    sealedSecrets: null, hasApiKey: false, hasCustomHeaders: false, maxOutputTokens: null, contextWindow: null,
    models: [{ id: 'test-model', longOutput: false, multimodal: false, tests: untestedConnections() }, { id: 'other-model', longOutput: false, multimodal: false, tests: untestedConnections() }], revision: 1, tests: untestedConnections() })
  store.saveService({ ...store.getService('local-test')!, id: 'prior-test', name: '先前服务' })
  store.setSettings({ ...store.getSettings(), activeProfileId: 'local-test' })
  store.enqueueInput(daily.id, '周末想去河边走走', null, 'daily-handoff-request')
  store.updateInputStatus('daily-handoff-request', 'completed')
  store.createTask({ id: 'daily-handoff-run', conversationId: daily.id, requestId: 'daily-handoff-request', generation: 0,
    status: 'completed', serviceId: 'prior-test', modelId: 'test-model', configRevision: 1, error: null, assistantMessageId: 'daily-handoff-answer' })
  const { manager } = await openConversationHistory(paths.root, daily)
  manager.appendCustomEntry('her.run', { runId: 'daily-handoff-run', profileId: 'prior-test',
    userMessageId: 'daily-handoff-source', assistantMessageId: 'daily-handoff-answer' })
  manager.appendMessage({ role: 'user', content: [{ type: 'text', text: '周末想去河边走走' }], timestamp: Date.now() })
  manager.appendMessage({ role: 'assistant', content: [{ type: 'text', text: '那一路上，有什么让你多看了一眼吗？' }], stopReason: 'stop', timestamp: Date.now(),
    api: 'openai-completions', provider: 'local-test', model: 'test-model', usage: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0,
      totalTokens: 0, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, total: 0 } } } as never)
  store.close()
  let running = await launch(directory)
  try {
    await expect(running.page.getByText('周末想去河边走走')).toBeVisible()
    const invite = running.page.locator('.handoff-invite')
    await expect(invite.getByRole('button', { name: '单独聊这件事' })).toBeVisible()
    await expect(running.page.locator('.chat-header').getByRole('button', { name: '单独聊这件事' })).toHaveCount(0)
    const message = await running.page.locator('.messages').boundingBox()
    const inviteBounds = await invite.boundingBox()
    expect(inviteBounds!.y).toBeGreaterThan(message!.y + message!.height - 1)
    await running.page.screenshot({ path: join(evidence, `${evidencePrefix}-daily-handoff-entry.png`) })
    const details = running.page.locator('.model-details')
    await details.getByLabel('对话详情').click()
    await expect(details.getByRole('heading', { name: '模型与能力' })).toBeVisible()
    await expect(details.getByLabel('当前模型', { exact: true })).toBeVisible()
    const rendererErrors: string[] = []
    running.page.on('pageerror', error => rendererErrors.push(error.message))
    await running.page.getByLabel('当前模型', { exact: true }).evaluate(select => {
      const blur = new FocusEvent('focusout', { bubbles: true })
      Object.defineProperty(blur, 'relatedTarget', { value: window })
      select.dispatchEvent(blur)
    })
    await expect(details).toHaveAttribute('open', '')
    await details.getByLabel('当前模型', { exact: true }).click()
    await details.getByLabel('当前模型', { exact: true }).selectOption('other-model')
    await expect(running.page.getByRole('heading', { name: '日常' })).toBeVisible()
    await expect(details.getByLabel('当前模型', { exact: true })).toHaveValue('other-model')
    expect(rendererErrors).toEqual([])
    await running.page.screenshot({ path: join(evidence, `${evidencePrefix}-daily-details-menu.png`) })
    await running.page.keyboard.press('Escape')
    await expect(details).not.toHaveAttribute('open', '')
    await running.page.getByRole('button', { name: '单独聊这件事' }).click()
    await expect(running.page.getByRole('dialog').getByText('你 · 来自日常 · 本次选定内容')).toBeVisible()
    await expect(running.page.getByRole('dialog').getByText('周末想去河边走走')).toBeVisible()
    await expect(running.page.getByRole('dialog').getByText('那一路上，有什么让你多看了一眼吗？')).toBeVisible()
    await expect(running.page.getByRole('dialog').getByText('Samantha · 来自日常 · 本次选定内容')).toBeVisible()
    await expect(running.page.getByRole('dialog').getByText('其中 1 条 Samantha 回复来自其他模型服务；确认后会作为背景提供给「隔离本地服务」。')).toBeVisible()
    await running.page.screenshot({ path: join(evidence, `${evidencePrefix}-handoff-preview.png`) })
    await running.page.getByRole('button', { name: '确认并另开话题' }).click()
    await expect(running.page.getByText('从日常带来的背景')).toBeVisible()
    const created = await running.page.evaluate(() => window.her.listWorkItems())
    expect(created).toHaveLength(1)
    expect(await running.page.evaluate(id => window.her.getConversationTask(id), created[0].conversation.id)).toBeNull()
    expect((await running.page.evaluate(id => window.her.getQueue(id), created[0].conversation.id)).items).toEqual([])
    await running.app.close()
    running = await launch(directory)
    await running.page.getByRole('button', { name: '一起在做的事', exact: true }).click()
    await running.page.getByRole('button', { name: created[0].conversation.title, exact: true }).click()
    await expect(running.page.getByText('从日常带来的背景')).toBeVisible()
    await expect(running.page.getByText('周末想去河边走走')).toBeVisible()
    await expect(running.page.getByText('Samantha 回应：那一路上，有什么让你多看了一眼吗？')).toBeVisible()
    await running.page.screenshot({ path: join(evidence, `${evidencePrefix}-handoff-reopened.png`) })
  } finally { await running.app.close(); rmSync(directory, { recursive: true, force: true }) }
})
